#!/usr/bin/env python3
"""Capture MuJoCo scene screenshots used by fixed-condition evaluation.

The script renders the same XML files used by
mujoco_test/test_script/eval_go2_policy_logger.py:
- flat:    mujoco_test/data/go2/scene.xml
- terrain: mujoco_test/data/go2/scene_terrain.xml

Push screenshots are the rendered scene with an annotation arrow overlaid. The
arrow documents the evaluation disturbance; it is not a fabricated simulation
result and no evaluation metrics are generated by this script.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import numpy as np


def preparse_gl_backend() -> None:
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--gl_backend", choices=["egl", "osmesa", "glfw"], default=None)
    args, _ = parser.parse_known_args()
    if args.gl_backend:
        os.environ["MUJOCO_GL"] = args.gl_backend


preparse_gl_backend()

os.environ.setdefault("MPLCONFIGDIR", "/tmp/matplotlib-cache")
os.environ.setdefault("XDG_CACHE_HOME", "/tmp")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

try:
    import mujoco  # noqa: E402
except Exception as exc:  # noqa: BLE001
    print(
        "ERROR: could not import mujoco. Activate the environment that was used "
        "for MuJoCo evaluation, for example `conda activate rlgpu`.",
        file=sys.stderr,
    )
    raise SystemExit(1) from exc


REPO_ROOT = Path(__file__).resolve().parents[1]
GO2_DATA_DIR = REPO_ROOT / "mujoco_test" / "data" / "go2"
DEFAULT_JOINT_ANGLES = np.array(
    [
        0.1,
        0.8,
        -1.5,
        -0.1,
        0.8,
        -1.5,
        0.1,
        1.0,
        -1.5,
        -0.1,
        1.0,
        -1.5,
    ],
    dtype=np.float64,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out_dir", type=Path, default=REPO_ROOT / "project_outputs" / "scene_screenshots")
    parser.add_argument("--width", type=int, default=1600)
    parser.add_argument("--height", type=int, default=1000)
    parser.add_argument("--gl_backend", choices=["egl", "osmesa", "glfw"], default=None)
    return parser.parse_args()


def make_data(scene_path: Path) -> tuple[mujoco.MjModel, mujoco.MjData]:
    if not scene_path.exists():
        raise FileNotFoundError(scene_path)
    model = mujoco.MjModel.from_xml_path(str(scene_path))
    data = mujoco.MjData(model)
    data.qpos[7:19] = DEFAULT_JOINT_ANGLES
    mujoco.mj_forward(model, data)
    return model, data


def make_camera(scene: str) -> mujoco.MjvCamera:
    camera = mujoco.MjvCamera()
    camera.type = mujoco.mjtCamera.mjCAMERA_FREE
    if scene == "terrain":
        camera.lookat[:] = [-1.25, 2.0, 0.35]
        camera.distance = 6.4
        camera.azimuth = 145.0
        camera.elevation = -25.0
    else:
        camera.lookat[:] = [-1.25, -0.25, 0.28]
        camera.distance = 2.4
        camera.azimuth = 135.0
        camera.elevation = -22.0
    return camera


def render_scene(scene_path: Path, scene: str, width: int, height: int) -> np.ndarray:
    model, data = make_data(scene_path)
    model.vis.global_.offwidth = max(model.vis.global_.offwidth, width)
    model.vis.global_.offheight = max(model.vis.global_.offheight, height)
    camera = make_camera(scene)
    try:
        renderer = mujoco.Renderer(model, height=height, width=width)
        renderer.update_scene(data, camera=camera)
        image = renderer.render()
        renderer.close()
    except Exception as exc:  # noqa: BLE001
        print(
            "ERROR: MuJoCo offscreen rendering failed. Try one of:\n"
            "  python tools/capture_mujoco_eval_scenes.py --gl_backend egl\n"
            "  python tools/capture_mujoco_eval_scenes.py --gl_backend osmesa\n"
            "or open the XML manually with the MuJoCo viewer and save screenshots.\n"
            f"Underlying error: {type(exc).__name__}: {exc}",
            file=sys.stderr,
        )
        raise SystemExit(1) from exc
    return image


def save_image(image: np.ndarray, out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    plt.imsave(out_path, image)
    print(f"Wrote {out_path}")


def save_push_annotation(image: np.ndarray, out_path: Path, title: str) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(10, 6.25), dpi=160)
    ax.imshow(image)
    ax.axis("off")
    ax.annotate(
        "40 N lateral push, 0.1 s\nDirection: +Y on base_link",
        xy=(0.58, 0.45),
        xytext=(0.30, 0.22),
        xycoords="axes fraction",
        textcoords="axes fraction",
        color="white",
        fontsize=12,
        fontweight="bold",
        arrowprops={"arrowstyle": "->", "lw": 3.0, "color": "tab:red"},
        bbox={"boxstyle": "round,pad=0.35", "fc": "black", "ec": "tab:red", "alpha": 0.65},
    )
    ax.set_title(title, color="white", fontsize=13, pad=8)
    fig.tight_layout(pad=0)
    fig.savefig(out_path, bbox_inches="tight", pad_inches=0.02)
    plt.close(fig)
    print(f"Wrote {out_path}")


def main() -> int:
    args = parse_args()
    flat_xml = GO2_DATA_DIR / "scene.xml"
    terrain_xml = GO2_DATA_DIR / "scene_terrain.xml"

    flat = render_scene(flat_xml, "flat", args.width, args.height)
    terrain = render_scene(terrain_xml, "terrain", args.width, args.height)

    save_image(flat, args.out_dir / "flat_scene.png")
    save_image(terrain, args.out_dir / "terrain_scene.png")
    save_push_annotation(flat, args.out_dir / "push_flat_0p4_scene.png", "Push Condition: flat_0p4")
    save_push_annotation(terrain, args.out_dir / "push_terrain_0p4_scene.png", "Push Condition: terrain_0p4")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
